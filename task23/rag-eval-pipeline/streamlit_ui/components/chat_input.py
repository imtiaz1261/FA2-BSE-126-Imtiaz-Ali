def finalize_generation(response_text: str) -> None:
    """
    Called by app.py after the backend returns a response.
    Adds the assistant message and marks generation as complete.
    """
    # Advance agents to done
    simulate_agent_progress(3)

    # Record timing
    start = st.session_state.get("exec_start_time")
    elapsed = (datetime.now() - start).total_seconds() if start else 0.0
    st.session_state["last_exec_time"] = elapsed

    add_message(
        "assistant",
        response_text,
        extra={"exec_time": elapsed},
    )

    st.session_state["is_generating"] = False
    set_notification("Response generated.", "success")
