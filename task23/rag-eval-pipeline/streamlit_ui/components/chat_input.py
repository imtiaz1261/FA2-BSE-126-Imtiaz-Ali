"""
components/chat_input.py
------------------------
Sticky chat input bar at the bottom of the main content area.

Responsibilities:
  - Render st.chat_input (Streamlit's native sticky input)
  - Consume st.session_state.pending_input pre-fills from prompt cards
  - Kick off the mock generation flow (placeholder)
  - Return the submitted text so app.py can route it

The actual AI call stays in app.py / the backend layer.
This module is purely UI + handoff.
"""

from __future__ import annotations

from datetime import datetime

import streamlit as st

from utils.session import (
    add_message,
    clear_pending_input,
    get_active_conversation,
    new_conversation,
    reset_agent_statuses,
    set_agent_status,
    set_notification,
    simulate_agent_progress,
)


# ──────────────────────────────────────────────────────────────────────────────
# Public renderer
# ──────────────────────────────────────────────────────────────────────────────

def render_chat_input() -> str | None:
    """
    Render the chat input bar and handle submission.

    Returns
    -------
    str | None
        The submitted user text if a message was just sent, else None.
        app.py uses this to trigger the backend call.
    """
    # ── Consume pending input from prompt cards ──────────────────────────────
    pending = st.session_state.get("pending_input", "")

    # st.chat_input does not accept a `value` param, so we display a hint
    # and clear pending after consumption.
    placeholder = (
        f"💡  {pending[:60]}…  (press Enter to send)"
        if pending
        else "Ask anything…"
    )

    submitted = st.chat_input(placeholder, key="main_chat_input")

    # If the user pressed Enter without a pending pre-fill, use what they typed.
    # If there's a pending prompt and they pressed Enter (submitted==""),
    # use the pending text.
    user_text: str | None = None

    if submitted:
        user_text = submitted.strip()
        clear_pending_input()
    elif pending and submitted is not None:
        # submitted is "" when Enter is pressed with empty field
        user_text = pending.strip()
        clear_pending_input()

    if not user_text:
        return None

    # ── Ensure an active conversation exists ────────────────────────────────
    if st.session_state.get("active_conv_id") is None:
        new_conversation()

    # ── Add user message to session ─────────────────────────────────────────
    add_message("user", user_text)

    # ── Reset & kick off placeholder agent animation ─────────────────────────
    reset_agent_statuses()
    set_agent_status("researcher", "running", "Searching…")
    st.session_state["is_generating"]  = True
    st.session_state["exec_start_time"] = datetime.now()

    return user_text


