# PATTERN MATCHING  (score-based, highest wins)
# ─────────────────────────────────────────────────────────────────────────────

def pick_pattern(prompt: str) -> str:
    pl = prompt.lower()
    scores: Dict[str, int] = {}
    for pname, pdata in PATTERNS.items():
        score = 0
        for kw in pdata["keywords"]:
            if kw in pl:
                # longer keyword = more specific = higher weight
                score += len(kw.split())
        scores[pname] = score

    best = max(scores, key=lambda k: scores[k])
    # if nothing matched at all, default to hello_world
    return best if scores[best] > 0 else "hello_world"


