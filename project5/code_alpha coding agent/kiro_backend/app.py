_store: Dict[str, dict] = {}


def _make_task(prompt: str, repo_path: str) -> dict:
    tid     = "task_" + uuid.uuid4().hex[:8]
    pname   = pick_pattern(prompt)
    pdata   = PATTERNS[pname]
    ext     = pdata["file_ext"]
    fname   = f"{tid}_{pname}.{ext}"
    fpath   = str(Path(repo_path).resolve() / fname)

    sub_tasks = [
        {"id": i, "name": name, "status": "pending", "detail": ""}
        for i, name in enumerate(pdata["subtasks"])
    ]

    return {
        "task_id":        tid,
        "prompt":         prompt,
        "status":         "pending",
        "pattern":        pname,
        "file_ext":       ext,
        "file_name":      fname,
        "file_path":      fpath,
        "sub_tasks":      sub_tasks,
        "generated_code": None,
        "logs":           [f"✓ Received: {prompt}"],
        "code_template":  pdata["code"],
        "repo_path":      repo_path,
    }


# ─────────────────────────────────────────────────────────────────────────────
# SYNCHRONOUS EXECUTION  (runs inside SSE stream so UI sees every step)
# ─────────────────────────────────────────────────────────────────────────────

async def _run_task(task: dict):
    """Advance every sub-task one at a time; update store in place."""
    task["status"] = "running"

    for st in task["sub_tasks"]:
        st["status"] = "running"
        task["logs"].append(f"▶ {st['name']}")
        await asyncio.sleep(0.4)          # simulate work
        st["status"] = "complete"
        st["detail"] = "done"
        task["logs"].append(f"✓ {st['name']}")

    # Write file
    try:
        code = task["code_template"]
        Path(task["file_path"]).write_text(code, encoding="utf-8")
        task["generated_code"] = code
        task["logs"].append(f"✓ File written → {task['file_name']}")
    except Exception as exc:
        task["logs"].append(f"✗ File write failed: {exc}")

    task["status"] = "complete"


