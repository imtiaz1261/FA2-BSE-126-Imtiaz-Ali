@app.get("/tasks/{task_id}/stream")
async def stream_task(task_id: str):
    """SSE stream — pushes a JSON snapshot after every sub-task update."""
    task = _store.get(task_id)
    if not task:
        raise HTTPException(404, "Task not found")

    async def generator():
        while True:
            payload = json.dumps(_task_out(task).dict())
            yield f"data: {payload}\n\n"
            if task["status"] in ("complete", "error"):
                break
            await asyncio.sleep(0.2)

    return StreamingResponse(generator(), media_type="text/event-stream",
                             headers={"Cache-Control": "no-cache",
                                      "X-Accel-Buffering": "no"})


@app.put("/tasks/{task_id}/code")
async def update_code(task_id: str, body: dict):
    """Allow the user to save edited code back to the file."""
    task = _store.get(task_id)
    if not task:
        raise HTTPException(404, "Task not found")
    new_code = body.get("code", "")
    task["generated_code"] = new_code
    try:
        Path(task["file_path"]).write_text(new_code, encoding="utf-8")
    except Exception as exc:
        raise HTTPException(500, f"File write failed: {exc}")
    return {"saved": True, "file_path": task["file_path"]}


